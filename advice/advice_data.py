def get_advice_data(qid: str, treatment: str, al_advice_source: int = 0, song_title: str = "") -> dict:
    """
    Return normalized advice dictionary for template rendering:
    - advice_tokens: list of 10 numbers (advised tokens per bin)
    - advice_reasoning: list of 10 strings (or empty list if no per-bin reasoning)
    - advice_header: title string (e.g. "Algorithmic Advice — Weight Allocation")
    - advice_subheader: subtitle string describing the advice source
    - advice_short_title: compact title string for the Round 2 left-column chart
    """
    if qid.startswith("weight"):
        task_topic = "Weight Allocation"
    elif qid.startswith("height"):
        task_topic = "Height Allocation"
    elif qid.startswith("urn"):
        task_topic = "Urn Allocation"
    elif qid.startswith("song"):
        task_topic = f"Song Ranking ({song_title})" if song_title else "Song Ranking"
    else:
        task_topic = "Token Allocation"

    if treatment == "algorithmic":
        model_name = ALGORITHMIC_MODEL_NAMES.get(al_advice_source, "AI Model")
        entry = ALGORITHMIC_ADVICE.get(qid, {}).get(al_advice_source, {"tokens": [10] * 10, "reasoning": []})
        return {
            "advice_tokens": entry["tokens"],
            "advice_reasoning": entry.get("reasoning", []),
            "advice_header": f"Algorithmic Advice — {task_topic}",
            "advice_subheader": f"The following advice was generated by {model_name}.",
            "advice_short_title": f"Algorithmic Advice — Token Allocation",
        }
    else:
        tokens = HUMAN_ADVICE_TOKENS.get(qid, [10.0] * 10)
        return {
            "advice_tokens": tokens,
            "advice_reasoning": [],
            "advice_header": f"Human Advice — {task_topic}",
            "advice_subheader": (
                "The following advice represents the average token allocation of "
                "40+ previous participants who completed this task without advice."
            ),
            "advice_short_title": "Human Advice — Token Allocation",
        }
